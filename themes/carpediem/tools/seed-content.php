$updated = 0;
$page_titles = array(
	'size-guide' => 'Как снять мерки',
);

foreach ( $pages as $slug => $content ) {
	$page = get_page_by_path( $slug );

	if ( ! $page ) {
		WP_CLI::warning( "Страница {$slug} не найдена" );
		continue;
	}

	wp_update_post( array(
		'ID'           => $page->ID,
		'post_content' => $content,
		'post_title'    => $page_titles[ $slug ] ?? $page->post_title,
	) );

	++$updated;
	WP_CLI::log( "{$slug} — обновлена" );
}

$size_guide_page = get_page_by_path( 'size-guide' );
if ( $size_guide_page ) {
	$menu_items = wp_get_nav_menu_items( 'Футер: Поддержка' );
	foreach ( (array) $menu_items as $menu_item ) {
		if ( (int) $size_guide_page->ID === (int) $menu_item->object_id ) {
			wp_update_post( array( 'ID' => $menu_item->ID, 'post_title' => 'Как снять мерки' ) );
		}
	}
}

WP_CLI::success( "Тексты добавлены: {$updated}" );
