$updated = 0;

foreach ( $pages as $slug => $content ) {
	$page = get_page_by_path( $slug );

	if ( ! $page ) {
		WP_CLI::warning( "Страница {$slug} не найдена" );
		continue;
	}

	wp_update_post( array(
		'ID'           => $page->ID,
		'post_content' => $content,
	) );

	++$updated;
	WP_CLI::log( "{$slug} — обновлена" );
}

WP_CLI::success( "Тексты добавлены: {$updated}" );
